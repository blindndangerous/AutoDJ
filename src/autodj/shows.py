@dataclass(frozen=True)
class PreviewShows:
    """What the hour preview needs of a station's shows, read once.

    Attributes:
        on_air: The show on the air and its songs not yet queued, or ``None``.
        scheduled: Each show a "Play a show" event names, by ID: its name
            and songs.
    """

    on_air: tuple[str, tuple[Any, ...]] | None = None
    scheduled: Mapping[str, tuple[str, tuple[Any, ...]]] = field(default_factory=dict)

    def signature(self) -> str:
        """The shows' names and songs, for the preview's cache."""

        def paths(entries: Sequence[Any]) -> list[str]:
            return [entry.path for entry in entries]

        on_air = (self.on_air[0], paths(self.on_air[1])) if self.on_air else None
        scheduled = sorted(
            (show_id, name, paths(entries)) for show_id, (name, entries) in self.scheduled.items()
        )
        return json.dumps([on_air, scheduled], ensure_ascii=False)


def preview_shows(
    store: ShowStore | None,
    runner: ShowRunner | None,
    events: Sequence[Any],
    entry_for_path: Callable[[str], Any],
) -> PreviewShows:
    """The shows the hour preview lists: the one on the air and every scheduled one.

    Songs no longer in the library are left out, as they are on the air.
    Blocking (reads the shows file).
    """

    def entries(paths: Sequence[str]) -> tuple[Any, ...]:
        found = (entry_for_path(path) for path in paths)
        return tuple(entry for entry in found if entry is not None)

    on_air = None
    if runner is not None and (upcoming := runner.upcoming()) is not None:
        on_air = (upcoming[0], entries(upcoming[1]))
    wanted = {
        str(event.params.get("show", ""))
        for event in events
        if getattr(event, "enabled", False) and event.action == "show"
    }
    scheduled: dict[str, tuple[str, tuple[Any, ...]]] = {}
    if wanted and store is not None:
        shows = store.all()
        for show_id in sorted(wanted):
            show = shows.get(show_id)
            if show is not None:
                scheduled[show_id] = (show.name, entries(show.songs))
    return PreviewShows(on_air, scheduled)


def songs_view(show: Show, entry_for_path: Callable[[str], Any]) -> tuple[list[dict], float]:
    """Each song of *show* for the page, and their total length in seconds."""
    rows: list[dict[str, Any]] = []
    total = 0.0
    for path in show.songs:
        entry = entry_for_path(path)
        if entry is None:
            rows.append(
                {
                    "path": path,
                    "title": _file_name(path),
                    "missing": True,
                    "seconds": 0,
                    "length_text": "",
                }
            )
            continue
        seconds = max(0.0, float(entry.length or 0.0))
        total += seconds
        rows.append(
            {
                "path": path,
                "title": song_title(entry),
                "missing": False,
                "seconds": round(seconds, 1),
                "length_text": length_text(seconds),
            }
        )
    return rows, total


def fresh_seed() -> int:
    """A seed for a generation: each one gives a new list."""
    return random.SystemRandom().randrange(10**9)


