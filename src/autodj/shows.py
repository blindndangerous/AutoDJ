def song_title(entry: Any) -> str:
    """ "Artist, Title" (a comma, which a screen reader pauses on)."""
    artist = (getattr(entry, "artist", "") or "").strip()
    title = (getattr(entry, "title", "") or "").strip() or getattr(entry, "display_name", "")
    return f"{artist}, {title}" if artist else (title or "Unknown")


