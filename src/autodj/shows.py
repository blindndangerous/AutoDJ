def prepared_entry(item: Any, library: Any) -> Any:
    """One owned occurrence, shared by edition playout and contextual review."""
    from autodj.indexer import IndexEntry

    entry: Any
    if item.kind == "song":
        original = library.entry_for_path(str(item.path))
        if original is None:
            return None
        entry = copy.copy(original)
    else:
        if not 0 < item.seconds <= 1800:
            raise ValueError("A standalone speech segment must be at most 30 minutes")
        entry = IndexEntry(
            path=str(item.path),
            title=item.label or "Speech segment",
            artist="",
            album="",
            genre="",
            bpm=0,
            year=0,
            length=item.seconds,
            energy=0.1,
            key=-1,
            mode=-1,
            tempo_confidence=0,
        )
        entry._prepared_clip = True
        entry._prepared_points = {
            "start": 0.0,
            "segue": item.seconds,
            "end": item.seconds,
        }
    entry._prepared_occurrence_id = item.occurrence_id
    return entry


def prepared_break(speech: Any) -> Any:
    """A validated local handoff take; no reservation, provider or live-slot state."""
    from autodj.breaks import Break, BreakCues

    return Break(
        break_id=speech.take_id,
        kind="dj",
        slot_id="",
        ending="",
        upcoming="",
        placement=speech.placement,
        allow_outro=speech.allow_outro,
        path=speech.path,
        size=0,
        cues=BreakCues(0, speech.seconds, speech.seconds, speech.seconds),
        label=speech.label or "Prepared speech",
        token_name="",  # nosec B106 — local asset attribution, not an authentication secret
        created_at=0,
        expires_at=0,
        source="prepared_edition",
        keep_file=True,
        limit_s=speech.seconds,
    )


@dataclass
class _OnAir:
    """The show on the air: its list as it was when it started, and how far it has got."""

    show_id: str
    name: str
    songs: tuple[str, ...]
    started_at: float
    # After this a show cut short by a restart is not resumed.
    ends_by: float
    next_index: int = 0
    # The show's own queue entries (copies, told apart by identity from a
    # listener's request of the same song), not yet seen leaving the queue.
    waiting: list[Any] = field(default_factory=list)
    # Each waiting copy's place in the list, by the copy's id().
    places: dict[int, int] = field(default_factory=dict)
    played: int = 0
    skipped: list[dict[str, str]] = field(default_factory=list)
    skipped_count: int = 0
    # Stop was asked for, but some of the show's entries are still queued.
    stopping: bool = False
    edition_id: str | None = None
    prepared: Any = None
    prepared_entries: tuple[Any, ...] = ()
    confirm_reair: bool = False
    marked_started: bool = False
    committed_audio_notice: str | None = None

    def resume_index(self) -> int:
        """The first place in the list that has not played: the earliest waiting copy's."""
        waiting = [self.places.get(id(entry), self.next_index) for entry in self.waiting]
        return min([*waiting, self.next_index])

    def skip(self, path: str, title: str, reason: str) -> None:
        self.skipped_count += 1
        if len(self.skipped) < MAX_SKIPPED:
            self.skipped.append({"path": path, "title": title, "reason": reason})

    def holds(self, entry: Any) -> bool:
        """Whether *entry* is one of the show's own waiting queue entries."""
        return any(entry is mine for mine in self.waiting)


def dmca_limits_at(bridge: Any, entry: Any, view: Any, position: int) -> tuple[str, ...]:
    """The DMCA limits *entry* would break at *position* of the user queue in *view*.

    Its start is timed as the hour preview times the queue (#217): after
    the playing song, any "play next" song and the queue before *position*
    (:meth:`~autodj._bridge.PlayerBridge.history_ahead`).  Empty when DMCA
    mode is off.  Never holds ``queue_lock`` while it works.
    """
    player = bridge.player
    if not player._cfg.dmca.enabled:
        return ()
    from autodj.dmca import complement

    waiting = [view.queued_next] if view.queued_next is not None else []
    index = len(waiting) + position
    waiting.extend(view.queue)
    records, when = bridge.history_ahead(waiting, index, entry)
    return tuple(complement(records, when, player._track_keys()).broken(entry))


#: A show cut short by a restart resumes only until its list would have
#: ended, counted from its start, plus this much (seconds).
RESUME_GRACE_S = 15 * 60
ON_AIR_VERSION = 1


class ShowRunner:
    """Air one station's shows: feed the queue from the list, check DMCA, end when it ends.

    Starting, song changes and stopping run on the event loop, one at a time;
    the queue work (a projection of the DMCA limits and a short compare and
    insert under ``queue_lock``) runs in a worker thread.  Nothing runs on the
    audio thread.  The show on the air is written to *state_path* as it goes,
    so a restart resumes it at the first song that had not played, unless
    its list would have ended by then.
    """

    def __init__(
        self,
        bridge: Any,
        store: ShowStore,
        publish: Callable[[dict[str, Any]], Awaitable[None]],
        *,
        state_path: Path | None = None,
        clock: Callable[[], float] = time.time,
        edition_store: Any = None,
        edition_station: Any = None,
    ) -> None:
        self._bridge = bridge
        self._store = store
        self._publisher = publish
        self._clock = clock
        self._state_path = state_path
        self._edition_start_lock = threading.Lock()
        self._edition_refresh_lock = threading.Lock()
        self._prepared_signature: str | None = None
        self._prepared_loop: asyncio.AbstractEventLoop | None = None
        self._prepared_refresh_task: asyncio.Task[None] | None = None
        self._prepared_refresh_requested = False
        self._turn = asyncio.Lock()
        # Guards _on_air for the preview and the request desk, which read it
        # from their own threads.
        self._state_lock = threading.Lock()
        self._edition_store = edition_store
        self._edition_station = edition_station
        self._interrupted: dict[str, Any] | None = None
        self._on_air: _OnAir | None = None
        self._tasks: set[asyncio.Task[None]] = set()
        self._resume: dict[str, Any] | None = self._read_state()
        self._ahead_failed = False
        # The saved show could not be removed; tried again at each song change.
        self._forget_later = False
        #: Set by the station: told the show's name when one starts, so the
        #: request desk can say queued requests now play after it.
        self.on_started: Callable[[str], None] | None = None

    # -- reading ---------------------------------------------------------

    def status(self) -> dict[str, Any] | None:
        """The show on the air, or one waiting to resume after a restart, or ``None``."""
        with self._state_lock:
            air = self._on_air
            saved = self._resume
            if air is None:
                if saved is None:
                    return copy.deepcopy(self._interrupted)
                total = len(saved["songs"])
                return {
                    "id": saved["show_id"],
                    "name": saved["name"],
                    "pending_resume": True,
                    "resume_at": min(int(saved["next_index"]), total) + 1,
                    "total": total,
                    "played": int(saved.get("played") or 0),
                    "waiting": 0,
                    "to_come": max(0, total - int(saved["next_index"])),
                    "skipped": [],
                    "skipped_count": int(saved.get("skipped_count") or 0),
                    "started_at": saved.get("started_at"),
                    "stopping": False,
                }
            total = len(air.songs)
            return {
                "id": air.show_id,
                "edition_id": air.edition_id,
                "name": air.name,
                "pending_resume": False,
                "total": total,
                "played": air.played,
                "waiting": len(air.waiting),
                "to_come": total - air.next_index,
                "skipped": list(air.skipped),
                "skipped_count": air.skipped_count,
                "started_at": air.started_at,
                "stopping": air.stopping,
                "estimated_seconds": air.prepared.estimated_seconds
                if air.prepared is not None
                else None,
                "interrupted_edition": copy.deepcopy(self._interrupted),
                "committed_audio_notice": air.committed_audio_notice,
            }

    def upcoming(self) -> tuple[str, tuple[str, ...]] | None:
        """The show on the air and its songs not yet queued, or ``None`` (any thread)."""
        with self._state_lock:
            air = self._on_air
            if air is None:
                return None
            return air.name, air.songs[air.next_index :]

    def on_air_name(self) -> str | None:
        """The name of the show on the air, or ``None`` (any thread)."""
        with self._state_lock:
            air = self._on_air
            return air.name if air is not None and not air.stopping else None

    #: Set by the station: the name of a show the schedule starts within the
    #: given seconds, or ``None``.
    starts_within: Callable[[float], str | None] | None = None

    def ahead(self, within_s: float) -> str | None:
        """The show on the air, or one due to start within *within_s* seconds (any thread)."""
        name = self.on_air_name()
        if name is None and self.starts_within is not None:
            try:
                name = self.starts_within(within_s)
            except Exception:
                # Said once, not with every request; requests then promise as usual.
                if not self._ahead_failed:
                    logger.exception("Could not read when the schedule's next show starts")
                self._ahead_failed = True
                return None
            self._ahead_failed = False
        return name

    def is_show_entry(self, entry: Any) -> bool:
        """Whether *entry* is one of the show's own waiting queue entries (any thread)."""
        with self._state_lock:
            return self._on_air is not None and self._on_air.holds(entry)

    def edition_active(self, edition_id: str) -> bool:
        with self._state_lock:
            return self._on_air is not None and self._on_air.edition_id == edition_id

    def prepared_handoff(
        self,
        current: Any,
        upcoming: Any,
        *,
        report_omissions: bool = True,
        plan: Any = None,
    ) -> tuple[Any, ...]:
        """Only the exact adjacent edition occurrences receive their approved take."""
        if upcoming is None or self._edition_store is None:
            return ()
        marks = attached(self._bridge.player, "_edition_occurrences")
        before, after = marks.get(current), marks.get(upcoming)
        with self._state_lock:
            air = self._on_air
        if air is None or air.edition_id is None or before is None or after is None:
            return ()
        # Approval/cue/media inputs are rechecked on the render worker, outside
        # queue and audio locks, rather than trusting admission-time approval.
        if plan is None:
            plan = self.prepared_plan()
        if plan is None:
            return ()
        if report_omissions:
            with self._state_lock:
                for reason in plan.omissions:
                    if not any(row["reason"] == reason for row in air.skipped):
                        air.skip("", "Prepared speech", reason)
        return tuple(
            prepared_break(take)
            for take in plan.handoffs.get((before.occurrence_id, after.occurrence_id), ())
        )

    @staticmethod
    def _plan_signature(plan: Any) -> str:
        return repr((plan.items, dict(plan.handoffs), plan.omissions))

    def prepared_plan(self) -> Any:
        with self._state_lock:
            air = self._on_air
        if air is None or air.edition_id is None:
            return None
        return self._edition_store.runtime_plan(air.edition_id, self._edition_station)

    def prepared_plan_valid(self, plan: Any) -> bool:
        return self.edition_active(plan.edition_id) and self._edition_store.plan_is_current(
            plan, self._edition_station
        )

    def request_prepared_refresh(self) -> None:
        """Queue-held callers only wake the existing event-loop control worker."""
        loop = self._prepared_loop
        if loop is not None and not loop.is_closed():
            loop.call_soon_threadsafe(self._schedule_prepared_refresh)

    def _schedule_prepared_refresh(self) -> None:
        self._prepared_refresh_requested = True
        if self._prepared_refresh_task is None or self._prepared_refresh_task.done():
            self._prepared_refresh_task = asyncio.create_task(self._refresh_prepared_control())
            self._tasks.add(self._prepared_refresh_task)
            self._prepared_refresh_task.add_done_callback(self._tasks.discard)

    async def _refresh_prepared_control(self) -> None:
        while self._prepared_refresh_requested:
            self._prepared_refresh_requested = False
            try:
                await asyncio.to_thread(self.prepared_changed)
            except (OSError, ValueError, RuntimeError):
                logger.exception("Prepared audio refresh failed after an edit")
                self.prepared_speech_failed(
                    "", "Prepared audio refresh failed; check edition before airing"
                )

    def prepared_render_token(self, plan: Any = None) -> str:
        with self._state_lock:
            air = self._on_air
        if air is None or air.edition_id is None:
            return ""
        if plan is None:
            plan = self._edition_store.runtime_plan(air.edition_id, self._edition_station)
        cfg = self._bridge.player._cfg
        return repr((self._plan_signature(plan), cfg.playback, cfg.breaks, cfg.replaygain))

    @contextlib.contextmanager
    def prepared_render_guard(self, token: str) -> Any:
        """Hold model/settings writers out between dependency check and bus swap.

        Reads and fingerprinting finish before acquiring bus/set locks. API
        mutations use this same edition-store lock and notify only after release.
        """
        from autodj.player import settings_lock

        lock = getattr(self._edition_store, "_lock", contextlib.nullcontext())
        cfg = self._bridge.player._cfg
        with lock:
            settings = repr((cfg.playback, cfg.breaks, cfg.replaygain))
            validated = self.prepared_render_token()
            # Only in-memory comparisons and the caller's bus swap hold the
            # process-wide settings lock; validation above may read large files.
            with settings_lock(self._bridge.player):
                yield (
                    token == validated
                    and cfg is self._bridge.player._cfg
                    and settings == repr((cfg.playback, cfg.breaks, cfg.replaygain))
                )

    def prepared_editable(
        self,
        edition_id: str,
        *,
        take_ids: set[str] | None = None,
        pair: tuple[str | None, str | None] | None = None,
    ) -> bool:
        """Edits cannot retract a prepared voice already committed to the bus."""
        if not self.edition_active(edition_id):
            return True
        player = self._bridge.player
        track = player._playing_render
        if track is None or player.bus is None:
            return True
        marks = attached(player, "_edition_occurrences")
        before, after = marks.get(track.entry), marks.get(track.next_entry)
        current_pair = (
            before.occurrence_id if before else None,
            after.occurrence_id if after else None,
        )
        with self._state_lock:
            air = self._on_air
            if air is None or air.edition_id != edition_id:
                return True
            protected = {identity for _at, identity, _end in track.break_events}
        protected.update(mark.take_id for mark in (before, after) if mark and mark.take_id)
        if not (protected if take_ids is None else protected & take_ids) and (
            pair is None or pair != current_pair
        ):
            return True
        boundary = player.prepared_tail_boundary(track)
        return player.bus.can_replace_unheard_tail(track, before_frame=boundary)

    def prepared_changed(self) -> None:
        """Revalidate changed editions off the audio thread, including future PCM."""
        with self._edition_refresh_lock:
            with self._state_lock:
                air = self._on_air
            if air is None or air.edition_id is None:
                return
            plan = self._edition_store.runtime_plan(air.edition_id, self._edition_station)
            signature = self._plan_signature(plan)
            if signature == self._prepared_signature:
                return
            valid = {row.occurrence_id for row in plan.items}
            player = self._bridge.player
            marks = attached(player, "_edition_occurrences")
            with player._state.queue_lock:
                player._state.queue[:] = [
                    entry
                    for entry in player._state.queue
                    if not (
                        getattr(entry, "_prepared_clip", False)
                        and (mark := marks.get(entry)) is not None
                        and mark.occurrence_id not in valid
                    )
                ]
                queued = player._state.queued_next
                if (
                    getattr(queued, "_prepared_clip", False)
                    and (mark := marks.get(queued)) is not None
                    and mark.occurrence_id not in valid
                ):
                    player._state.queued_next = None
            for omission in plan.omissions:
                self.prepared_speech_failed("", omission)
            player.refresh_prepared_tail(plan)
            self._prepared_signature = signature

    def prepared_primary_valid(self, entry: Any, *, plan: Any = None) -> bool:
        """Recheck approval and the immutable asset at the last render boundary."""
        mark = attached(self._bridge.player, "_edition_occurrences").get(entry)
        with self._state_lock:
            air = self._on_air
        if mark is None or air is None or air.edition_id is None:
            return False
        try:
            if plan is None:
                plan = self._edition_store.runtime_plan(air.edition_id, self._edition_station)
            valid = any(
                row.occurrence_id == mark.occurrence_id
                and row.take_id == mark.take_id
                and row.path == mark.path
                for row in plan.items
            )
        except (OSError, ValueError):
            valid = False
        if not valid:
            self.prepared_speech_failed(
                mark.take_id or mark.occurrence_id,
                f"{mark.label}: changed, unapproved or missing; speech skipped",
            )
        return valid

    def prepared_render_committed(self, *entries: Any) -> None:
        """Persist a conservative may-have-aired guard before PCM can escape."""
        marks = attached(self._bridge.player, "_edition_occurrences")
        if not any(marks.get(entry) is not None for entry in entries if entry is not None):
            return
        with self._edition_start_lock:
            with self._state_lock:
                air = self._on_air
            if air is None or air.edition_id is None or air.marked_started:
                return
            self._edition_store.mark_started(air.edition_id, confirm_reair=air.confirm_reair)
            air.marked_started = True
            try:
                self._write_state(air, strict=True)
            except OSError:
                logger.exception(
                    "Could not save prepared edition progress; airing guard is durable"
                )

    def prepared_audio_committed(self) -> None:
        """An edit cannot revoke the prior approval of already committed PCM."""
        with self._state_lock:
            if self._on_air is not None and self._on_air.edition_id is not None:
                self._on_air.committed_audio_notice = (
                    "The current transition crossed its playout commit boundary under its "
                    "previous approval. Saved changes apply to future audio; current "
                    "committed audio continues."
                )

    def prepared_speech_failed(self, take_id: str, reason: str) -> None:
        with self._state_lock:
            if (
                self._on_air is not None
                and self._on_air.edition_id is not None
                and not any(row["reason"] == reason for row in self._on_air.skipped)
            ):
                self._on_air.skip("", take_id, reason)

    # -- the saved place --------------------------------------------------

    def _read_state(self) -> dict[str, Any] | None:
        path = self._state_path
        if path is None:
            return None
        try:
            saved = json.loads(path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            return None
        except (OSError, ValueError):
            logger.warning("The saved show on the air in %s cannot be read; not resumed", path)
            return None
        if isinstance(saved, dict) and saved.get("stopped") is True:
            self._interrupted = saved.get("interrupted_edition")
            return None
        fields_ok = (
            isinstance(saved, dict)
            and saved.get("version") == ON_AIR_VERSION
            and isinstance(saved.get("show_id"), str)
            and isinstance(saved.get("name"), str)
            and isinstance(saved.get("songs"), list)
            and all(isinstance(song, str) for song in saved["songs"])
            and isinstance(saved.get("next_index"), int)
            and isinstance(saved.get("ends_by"), (int, float))
        )
        if not fields_ok:
            logger.warning("The saved show on the air in %s is not valid; not resumed", path)
            return None
        self._interrupted = saved.get("interrupted_edition")
        if saved.get("edition_id"):
            self._interrupted = self._interrupted_status(saved)
            return None
        return dict(saved)

    @staticmethod
    def _interrupted_status(saved: Mapping[str, Any]) -> dict[str, Any]:
        return {
            "id": saved["edition_id"],
            "edition_id": saved["edition_id"],
            "name": saved["name"],
            "interrupted": True,
            "pending_resume": False,
            "resume_occurrence": saved.get("resume_occurrence"),
            "occurrences": list(saved.get("occurrences", ())),
            "total": len(saved.get("songs", ())),
            "played": saved.get("played", 0),
            "waiting": 0,
            "to_come": 0,
            "skipped": [],
            "skipped_count": 0,
        }

    def _forget_state(self) -> bool:
        """Remove the saved show, or leave a stopped marker; whether that worked.

        A file that cannot be removed (held open, say) is replaced by a marker
        that :meth:`_read_state` honours, and the removal is tried again with
        the next song change, so a stopped show never resumes.
        """
        path = self._state_path
        if path is None:
            return True
        for _try in range(3):
            try:
                path.unlink(missing_ok=True)
                self._forget_later = False
                return True
            except OSError:
                time.sleep(0.05)
        try:
            atomic_write(path, json.dumps({"version": ON_AIR_VERSION, "stopped": True}) + "\n")
        except OSError:
            logger.exception("Could not forget the saved show on the air in %s", path)
        else:
            logger.warning("Could not remove %s; left a stopped marker in it", path)
        self._forget_later = True
        return False

    def _write_state(self, air: _OnAir | None, *, strict: bool = False) -> None:
        """Save the show on the air (or forget it); a failure is logged, never raised."""
        path = self._state_path
        if path is None:
            return
        if air is None:
            if self._interrupted is not None:
                try:
                    atomic_write(
                        path,
                        json.dumps(
                            {
                                "version": ON_AIR_VERSION,
                                "stopped": True,
                                "interrupted_edition": self._interrupted,
                            }
                        )
                        + "\n",
                    )
                except OSError:
                    logger.exception("Could not save the interrupted edition to %s", path)
                return
            self._forget_state()
            return
        try:
            with self._state_lock:
                document = {
                    "version": ON_AIR_VERSION,
                    "show_id": air.show_id,
                    "name": air.name,
                    "songs": list(air.songs),
                    # The first song that has not played: the waiting ones
                    # leave the queue with a restart.
                    "next_index": air.resume_index(),
                    "played": air.played,
                    "skipped_count": air.skipped_count,
                    "started_at": air.started_at,
                    "ends_by": air.ends_by,
                    "interrupted_edition": self._interrupted,
                }
                if air.edition_id is not None:
                    rows = air.prepared.items
                    index = min(air.resume_index(), max(0, len(rows) - 1))
                    resume = next(
                        (
                            row.occurrence_id
                            for row in (*rows[index:], *reversed(rows[:index]))
                            if row.take_id != row.occurrence_id
                        ),
                        None,
                    )
                    document.update(
                        edition_id=air.edition_id,
                        occurrences=[
                            {"id": row.occurrence_id, "label": row.label, "kind": row.kind}
                            for row in rows
                        ],
                        resume_occurrence=resume,
                    )
            path.parent.mkdir(parents=True, exist_ok=True)
            atomic_write(path, json.dumps(document, ensure_ascii=False) + "\n")
        except OSError:
            logger.exception("Could not save the show on the air to %s", path)
            if strict:
                raise

    def _ends_by(self, songs: Sequence[str], start: float) -> float:
        """When a list started at *start* would have ended, plus the resume grace."""
        total = 0.0
        for path in songs:
            entry = self._bridge.entry_for_path(path)
            if entry is not None:
                total += max(0.0, float(entry.length or 0.0))
        return start + total + RESUME_GRACE_S

    # -- changing --------------------------------------------------------

    async def _publish(self) -> None:
        try:
            await self._publisher({"type": "shows_changed"})
        except Exception:
            logger.exception("Could not tell the web pages about a show change")

    async def start_edition(
        self,
        edition_id: str,
        *,
        now: bool = False,
        confirm_reair: bool = False,
        from_occurrence: str | None = None,
    ) -> str:
        """Queue a frozen local edition; restart resumption always names an item."""
        if self._edition_store is None or not self._plays_now_on_bus():
            raise ValueError("Prepared editions require server audio or streaming")
        if (
            self._interrupted is not None
            and self._interrupted.get("edition_id") == edition_id
            and from_occurrence is None
        ):
            raise ValueError("Choose an occurrence to resume this interrupted edition")
        plan = await asyncio.to_thread(
            self._edition_store.runtime_plan,
            edition_id,
            self._edition_station,
            from_occurrence=from_occurrence,
        )
        if plan.previously_started and not confirm_reair:
            raise ValueError("Confirm re-airing this edition; its speech has aired before")
        entries = tuple(prepared_entry(row, self._bridge.library) for row in plan.items)
        if not any(entry is not None for entry in entries):
            raise ValueError("This edition has no playable items")
        started = self._clock()
        air = _OnAir(
            edition_id,
            plan.name,
            tuple(str(row.path) for row in plan.items),
            started,
            started + plan.estimated_seconds + RESUME_GRACE_S,
            edition_id=edition_id,
            prepared=plan,
            prepared_entries=entries,
            confirm_reair=confirm_reair,
        )
        for omission in plan.omissions:
            air.skip("", "Prepared speech", str(omission))
        async with self._turn:
            await asyncio.to_thread(self._interrupt_edition)
            if not await asyncio.to_thread(self._clear_blocking):
                raise ValueError("The previous show is still being taken out of the queue")
            with self._state_lock:
                self._resume = None
                if (
                    self._interrupted is not None
                    and self._interrupted.get("edition_id") == edition_id
                ):
                    self._interrupted = None
            attached(self._bridge.player, "_edition_occurrences", create=True).clear()
            self._prepared_signature = self._plan_signature(plan)
            self._prepared_loop = asyncio.get_running_loop()
            self._bridge.player.request_prepared_refresh = self.request_prepared_refresh
            self._bridge.player.prepared_render_token = self.prepared_render_token
            self._bridge.player.prepared_plan = self.prepared_plan
            self._bridge.player.prepared_plan_valid = self.prepared_plan_valid
            self._bridge.player.prepared_render_guard = self.prepared_render_guard
            self._bridge.player.prepared_primary_valid = self.prepared_primary_valid
            self._bridge.player.prepared_render_committed = self.prepared_render_committed
            self._bridge.player.prepared_handoff = self.prepared_handoff
            self._bridge.player.prepared_preview_handoff = partial(
                self.prepared_handoff, report_omissions=False
            )
            self._bridge.player.prepared_speech_failed = self.prepared_speech_failed
            self._bridge.player.prepared_audio_committed = self.prepared_audio_committed
            queued, _skipped = await self._begin(
                air, now=now or self._bridge.player._state.current_track is None
            )
        await self._tell_started(plan.name)
        await self._publish()
        return f"Prepared edition {plan.name} queued ({queued} items)"

    def _interrupt_edition(self) -> None:
        with self._state_lock:
            air = self._on_air
            if air is None or air.edition_id is None:
                return
            rows = air.prepared.items
            index = min(air.resume_index(), max(0, len(rows) - 1))
            self._interrupted = self._interrupted_status(
                {
                    "edition_id": air.edition_id,
                    "name": air.name,
                    "songs": air.songs,
                    "played": air.played,
                    "resume_occurrence": rows[index].occurrence_id if rows else None,
                    "occurrences": [
                        {"id": row.occurrence_id, "label": row.label, "kind": row.kind}
                        for row in rows
                    ],
                }
            )

    def _entry_at(self, air: _OnAir, index: int) -> Any:
        if air.edition_id is None:
            return self._bridge.entry_for_path(air.songs[index])
        return air.prepared_entries[index]

    def _own_entry(self, air: _OnAir, entry: Any, index: int) -> Any:
        own = copy.copy(entry)
        if air.edition_id is not None:
            attached(self._bridge.player, "_edition_occurrences", create=True)[own] = (
                air.prepared.items[index]
            )
        return own

    def _plays_now_on_bus(self) -> bool:
        bridge = self._bridge
        return bool(getattr(bridge, "stream_mode", False) or bridge._bus_mode())

    async def start(self, show_id: str, *, now: bool = False) -> str:
        """Put the show on the air: its first songs go to the front of the queue.

        With *now* (a hard event) its first song plays at once, fading out
        the song playing, in every playback mode; a "play next" song the
        operator chose plays right after it.  Otherwise it follows the song
        playing.  A show already on the air stops first, and its waiting
        songs leave the queue; a show waiting to resume after a restart is
        forgotten.

        Returns:
            What happened, in words.

        Raises:
            ValueError: The show is gone, has no songs, nothing is playing,
                the show before it could not be taken out of the queue yet,
                or none of its songs could be queued.
        """
        show = await asyncio.to_thread(self._store.get, show_id)
        if show is None:
            raise ValueError("That show no longer exists")
        if not show.songs:
            raise ValueError(f"Show {show.name} has no songs; generate its list first")
        if self._bridge.player._state.current_track is None:
            raise ValueError(f"Nothing is playing, so show {show.name} did not start")
        songs = tuple(show.songs)
        started = self._clock()
        ends_by = await asyncio.to_thread(self._ends_by, songs, started)
        air = _OnAir(show_id, show.name, songs, started, ends_by)
        async with self._turn:
            await asyncio.to_thread(self._interrupt_edition)
            with self._state_lock:
                self._resume = None
            if not await asyncio.to_thread(self._clear_blocking):
                raise ValueError(
                    f"Show {show.name} did not start: the show before it is still being "
                    "taken out of the queue. Try again in a moment."
                )
            queued, skipped = await self._begin(air, now=now)
        await self._publish()
        if not queued:
            raise ValueError(
                f"Show {show.name} did not start: none of its songs could be queued "
                f"({skipped} skipped; see the log)"
            )
        logger.info("Show %r started: %d songs", show.name, len(songs))
        await self._tell_started(show.name)
        return f"Show {show.name} started: {len(songs)} songs."

    async def _tell_started(self, name: str) -> None:
        told = self.on_started
        if told is None:
            return
        try:
            await asyncio.to_thread(told, name)
        except Exception:
            logger.exception("Could not tell the request desk that show %r started", name)

    async def _begin(self, air: _OnAir, *, now: bool) -> tuple[int, int]:
        """Put *air* on the air (hold ``_turn``); how many songs it queued and skipped."""
        with self._state_lock:
            self._on_air = air
        first = None
        on_bus = now and self._plays_now_on_bus()
        if on_bus:
            first = await asyncio.to_thread(self._first_now_blocking, air)
        # The songs after the first are queued before it starts, so its
        # render is followed by the show's second song.
        await asyncio.to_thread(self._feed_blocking)
        if first is not None:
            # Play now leaves a "play next" song where it is: it plays next.
            if air.edition_id is not None:
                await asyncio.to_thread(self.prepared_render_committed, first)
                await asyncio.to_thread(self._bridge.play_next_entry, first, True)
            else:
                await asyncio.to_thread(self._bridge.play_next, first.path, True)
        elif now and not on_bus:
            with self._state_lock:
                started = bool(air.waiting)
            if started:
                # Browser playback: the operator's "play next" song moves to
                # just after the show's first song, then the skip plays that.
                await asyncio.to_thread(self._bridge.requeue_play_next, 1)
                await asyncio.to_thread(self._bridge.skip)
        with self._state_lock:
            queued = len(air.waiting) + (first is not None)
            skipped = air.skipped_count
            ended = self._on_air is air and not air.waiting and first is None
            if ended:
                self._on_air = None
        await asyncio.to_thread(self._write_state, None if ended else air)
        return queued, skipped

    async def stop(self) -> dict[str, Any] | None:
        """Take the show off the air, or forget one waiting to resume.

        Its own waiting entries leave the queue.  One that cannot be taken
        out yet (the queue keeps changing) is tried again with each song
        change, and the show stays "stopping" until then.

        Returns:
            ``{"name", "done"}``, or ``None`` when there was no show.
        """
        async with self._turn:
            with self._state_lock:
                interrupted = self._interrupted
                air = self._on_air
                saved, self._resume = self._resume, None
                if air is None and saved is None:
                    self._interrupted = None
            if air is None:
                if saved is None:
                    if interrupted is not None:
                        await asyncio.to_thread(self._forget_state)
                        return {"name": interrupted["name"], "done": True}
                    return None
                await asyncio.to_thread(self._write_state, None)
                logger.info("Show %r will not resume: stopped by the operator", saved["name"])
                await self._publish()
                return {"name": str(saved["name"]), "done": True}
            done = await asyncio.to_thread(self._clear_blocking)
        if done:
            logger.info("Show %r stopped by the operator", air.name)
        else:
            logger.warning(
                "Show %r is stopping: some of its songs could not be taken out of the queue "
                "yet; trying again at the next song change",
                air.name,
            )
        await self._publish()
        return {"name": air.name, "done": done}

    def track_changed(self) -> None:
        """Queue the show's next songs after a song change, or resume one (event loop)."""
        with self._state_lock:
            idle = self._on_air is None
            resume = self._resume is not None
        if idle and not resume and not self._forget_later:
            return
        if idle and not resume:
            work = self._retry_forget()
        else:
            work = self._resume_saved() if idle else self._after_change()
        task = asyncio.get_running_loop().create_task(work)
        self._tasks.add(task)
        task.add_done_callback(self._tasks.discard)

    async def _retry_forget(self) -> None:
        async with self._turn:
            if self._forget_later and self._on_air is None and self._resume is None:
                await asyncio.to_thread(self._forget_state)

    async def _after_change(self) -> None:
        try:
            async with self._turn:
                changed = await asyncio.to_thread(self._feed_blocking)
        except Exception:
            logger.exception("Could not queue the show's next songs")
            return
        if changed:
            await self._publish()

    async def _resume_saved(self) -> None:
        """Resume the show a restart cut short, once something plays; or forget it."""
        async with self._turn:
            with self._state_lock:
                saved, self._resume = self._resume, None
            if saved is None or self._on_air is not None:
                return
            if self._clock() > float(saved["ends_by"]):
                logger.info(
                    "Show %r was on the air before the restart; its time has passed, "
                    "so it is not resumed",
                    saved["name"],
                )
                await asyncio.to_thread(self._forget_state)
                await self._publish()
                return
            songs = tuple(saved["songs"])
            start_at = max(0, min(int(saved["next_index"]), len(songs)))
            air = _OnAir(
                str(saved["show_id"]),
                str(saved["name"]),
                songs,
                float(saved.get("started_at") or self._clock()),
                float(saved["ends_by"]),
                next_index=start_at,
                played=int(saved.get("played") or 0),
                skipped_count=int(saved.get("skipped_count") or 0),
            )
            try:
                queued, _skipped = await self._begin(air, now=False)
            except Exception:
                logger.exception("Could not resume show %r", air.name)
                return
        if queued:
            logger.info(
                "Show %r resumed after a restart at song %d of %d",
                air.name,
                start_at + 1,
                len(songs),
            )
            await self._tell_started(air.name)
        await self._publish()

    def _first_now_blocking(self, air: _OnAir) -> Any:
        """The first song that can play at once, counted as played; ``None`` when none can.

        Songs not in the library, and in DMCA mode songs that would break a
        limit if they started now, are skipped.
        """
        bridge = self._bridge
        while air.next_index < len(air.songs):
            path = air.songs[air.next_index]
            entry = self._entry_at(air, air.next_index)
            if entry is None:
                reason, title = "it is not in the library", _file_name(path)
            else:
                broken = (
                    ()
                    if getattr(entry, "_prepared_clip", False)
                    else bridge.dmca_queue_limits(entry, now=True, append=False)
                )
                if not broken:
                    with self._state_lock:
                        air.next_index += 1
                        air.played += 1
                    return (
                        self._own_entry(air, entry, air.next_index - 1)
                        if air.edition_id is not None
                        else entry
                    )
                reason, title = (
                    "it would break the DMCA limit: " + "; ".join(broken),
                    song_title(entry),
                )
            logger.warning("Show %r: %s skipped: %s", air.name, title, reason)
            with self._state_lock:
                air.next_index += 1
                air.skip(path, title, reason)
        return None

    def _remove_own_blocking(self, air: _OnAir) -> bool:
        """Take *air*'s own entries out of the queue; whether none is left.

        It counts first what already left the queue, then removes each of the
        show's entries by its place in the queue as read (only if the queue is
        unchanged), never a listener's request or the operator's song for the
        same file.
        """
        bridge = self._bridge
        for _step in range(4 * (len(air.waiting) + 2)):
            view = bridge._queue_view()
            with self._state_lock:
                self._account(air, view)
                if not air.waiting:
                    return True
                index = next((i for i, entry in enumerate(view.queue) if air.holds(entry)), None)
            if index is None:
                # Only in "play next", which a show never uses: nothing to take.
                return True
            removed = view.queue[index]
            if bridge.queue_remove_if(index, view):
                with self._state_lock:
                    air.waiting = [mine for mine in air.waiting if mine is not removed]
                    air.places.pop(id(removed), None)
        with self._state_lock:
            return not air.waiting

    def _clear_blocking(self) -> bool:
        """Take the show off the air once its own entries are out of the queue.

        Returns:
            Whether it is off the air.  When some entries could not be taken
            out (the queue kept changing), the show stays on as "stopping",
            feeds nothing more, and is tried again at each song change.
        """
        with self._state_lock:
            air = self._on_air
            if air is not None:
                air.stopping = True
        if air is None:
            self._forget_state()
            return True
        if not self._remove_own_blocking(air):
            return False
        with self._state_lock:
            if self._on_air is air:
                self._on_air = None
        self._write_state(None)
        return True

    def _account(self, air: _OnAir, view: Any) -> bool:
        """Count the show's entries that left the queue (played, or removed by hand)."""
        present = [view.queued_next] if view.queued_next is not None else []
        present.extend(view.queue)
        kept = [mine for mine in air.waiting if any(mine is entry for entry in present)]
        changed = len(kept) != len(air.waiting)
        air.played += len(air.waiting) - len(kept)
        for gone in air.waiting:
            if not any(gone is mine for mine in kept):
                air.places.pop(id(gone), None)
        air.waiting = kept
        return changed

    def _feed_blocking(self) -> bool:
        """Bring the show's waiting songs up to :data:`AHEAD`; whether anything changed.

        Each step reads the queue with no lock held, works out the DMCA limits
        from that copy, then inserts or removes under ``queue_lock`` only if
        the queue is unchanged (otherwise it reads again).  Bounded by the
        length of the list.
        """
        bridge = self._bridge
        with self._state_lock:
            air = self._on_air
        if air is None:
            return False
        if air.stopping:
            # Stop could not take every entry out yet: try again, feed nothing.
            if self._remove_own_blocking(air):
                with self._state_lock:
                    if self._on_air is air:
                        self._on_air = None
                logger.info("Show %r stopped: its songs are out of the queue", air.name)
                self._forget_state()
                return True
            return False
        changed = False
        for _step in range(len(air.songs) + 3 * AHEAD + 10):
            view = bridge._queue_view()
            with self._state_lock:
                if self._on_air is not air:
                    return changed
                changed = self._account(air, view) or changed
                mine = [air.holds(entry) for entry in view.queue]
            # A waiting show song that would now break a DMCA limit (something
            # was queued before it, say) leaves the queue.
            recheck = next(
                (
                    (index, entry, broken)
                    for index, entry in enumerate(view.queue)
                    if mine[index]
                    and not getattr(entry, "_prepared_clip", False)
                    and (broken := dmca_limits_at(bridge, entry, view, index))
                ),
                None,
            )
            if recheck is not None:
                index, entry, broken = recheck
                if bridge.queue_remove_if(index, view):
                    reason = "it would break the DMCA limit: " + "; ".join(broken)
                    logger.warning("Show %r: %s skipped: %s", air.name, entry.display_name, reason)
                    with self._state_lock:
                        air.waiting = [item for item in air.waiting if item is not entry]
                        air.places.pop(id(entry), None)
                        air.skip(entry.path, song_title(entry), reason)
                    changed = True
                continue
            if len(air.waiting) >= AHEAD or air.next_index >= len(air.songs):
                break
            path = air.songs[air.next_index]
            entry = self._entry_at(air, air.next_index)
            if entry is None:
                logger.warning("Show %r: %s skipped: it is not in the library", air.name, path)
                with self._state_lock:
                    air.next_index += 1
                    air.skip(path, _file_name(path), "it is not in the library")
                changed = True
                continue
            # After the show's last waiting song, or first in the queue: ahead
            # of songs queued before the show, listener requests included.
            position = max((index + 1 for index, held in enumerate(mine) if held), default=0)
            broken = (
                ()
                if getattr(entry, "_prepared_clip", False)
                else dmca_limits_at(bridge, entry, view, position)
            )
            if broken:
                reason = "it would break the DMCA limit: " + "; ".join(broken)
                logger.warning("Show %r: %s skipped: %s", air.name, entry.display_name, reason)
                with self._state_lock:
                    air.next_index += 1
                    air.skip(path, song_title(entry), reason)
                changed = True
                continue
            # The show's own copy, so it is told apart from a listener's
            # request or the operator's song for the same file.
            own = self._own_entry(air, entry, air.next_index)
            if bridge.queue_insert_if(own, position, view):
                with self._state_lock:
                    air.places[id(own)] = air.next_index
                    air.next_index += 1
                    air.waiting.append(own)
                changed = True
        ended = False
        with self._state_lock:
            prepared_playing = (
                air.edition_id is not None
                and attached(self._bridge.player, "_edition_occurrences").get(
                    self._bridge.player._state.current_track
                )
                is not None
            )
            if (
                self._on_air is air
                and air.next_index >= len(air.songs)
                and not air.waiting
                and not prepared_playing
            ):
                self._on_air = None
                ended = True
                logger.info(
                    "Show %r ended: %d played, %d skipped; normal programming resumes",
                    air.name,
                    air.played,
                    air.skipped_count,
                )
                changed = True
        if changed:
            self._write_state(None if ended else air)
        return changed


def show_action(runner: ShowRunner, store: ShowStore, editions: Any = None) -> Any:
    """The scheduler's "Play a show" action.

    Hard timing plays the show's first song at once, fading out the song
    playing; soft timing queues it when the event is due, to follow the song
    playing without cutting it.
    """
    from autodj.scheduler import Action, ActionField

    def choices() -> list[tuple[str, str]]:
        shows = store.all()
        found = [(show_id, show.name) for show_id, show in shows.items()]
        if editions is not None:
            for identity, edition in editions.all().items():
                found.append((f"edition:{identity}", f"Prepared edition: {edition.name}"))
                if edition.previously_started:
                    found.append(
                        (
                            f"edition-confirmed:{identity}",
                            f"Re-air prepared edition: {edition.name} (speech may have aired)",
                        )
                    )
        return sorted(found, key=lambda pair: pair[1].casefold())

    async def start(value: str, *, now: bool = False) -> None:
        prefix, _, identity = value.partition(":")
        if prefix in {"edition", "edition-confirmed"}:
            await runner.start_edition(
                identity, now=now, confirm_reair=prefix == "edition-confirmed"
            )
        else:
            await runner.start(value, now=now)

    async def play(params: dict[str, str]) -> None:
        await start(params["show"])

    async def play_now(params: dict[str, str]) -> None:
        await start(params["show"], now=True)

    return Action(
        "show",
        "Play a show",
        play,
        (ActionField("show", "Show", more=choices),),
        "none",
        hard=play_now,
        soft_waits=False,
    )


