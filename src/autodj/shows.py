def length_text(seconds: float) -> str:
    """ "1:02:05" or "4:05": a length as a clock shows it."""
    total = max(0, round(seconds))
    hours, rest = divmod(total, 3600)
    minutes, secs = divmod(rest, 60)
    return f"{hours}:{minutes:02d}:{secs:02d}" if hours else f"{minutes}:{secs:02d}"


def length_words(seconds: float) -> str:
    """ "1 hour 2 minutes 5 seconds": a length in words, for a screen reader."""
    total = max(0, round(seconds))
    hours, rest = divmod(total, 3600)
    minutes, secs = divmod(rest, 60)
    parts = [
        f"{count} {unit}{'' if count == 1 else 's'}"
        for count, unit in ((hours, "hour"), (minutes, "minute"), (secs, "second"))
        if count
    ]
    return " ".join(parts) or "0 seconds"


def song_title(entry: Any) -> str:
    """ "Artist, Title" (a comma, which a screen reader pauses on)."""
    artist = (getattr(entry, "artist", "") or "").strip()
    title = (getattr(entry, "title", "") or "").strip() or getattr(entry, "display_name", "")
    return f"{artist}, {title}" if artist else (title or "Unknown")


def _file_name(path: str) -> str:
    return re.split(r"[\\/]", path)[-1] or path


