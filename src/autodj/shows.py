class ShowStore:
    """One station's ``shows.json``: read again whenever it changes on disk.

    Every method is blocking (file I/O): the routes call it in a worker thread.
    """

    def __init__(self, path: Path) -> None:
        self.path = Path(path)
        self._lock = threading.Lock()
        self._stamp: tuple[int, int, int] | None = None
        self._shows: dict[str, Show] = {}
        # Entries that are not valid shows, written back as they were.
        self._skipped: dict[str, Any] = {}

    def _stat(self) -> tuple[int, int, int] | None:
        return file_signature(self.path)

    def _keep_bad_copy(self, reason: str) -> None:
        """Set the invalid file aside.

        Raises:
            OSError: It could not be set aside: nothing may be written over it.
        """
        if not set_aside(self.path, "shows file", reason):
            raise OSError(
                f"The shows file {self.path.name} is not valid and could not be set aside; "
                "nothing is saved over it"
            )

    def _load_locked(self) -> dict[str, Show]:
        """Every show, read again if the file changed.  Caller holds ``_lock``.

        Raises:
            OSError: The file could not be looked at or read.
        """
        stamp = self._stat()
        if stamp == self._stamp:
            return dict(self._shows)
        shows: dict[str, Show] = {}
        skipped: dict[str, Any] = {}
        if stamp is not None:
            data = self.path.read_bytes()
            try:
                document = _ShowsFile.model_validate_json(data)
            except ValueError as exc:
                # Raises when it cannot be moved, so a save never writes over it.
                self._keep_bad_copy(str(exc).splitlines()[0])
                stamp = None
            else:
                for show_id, raw in document.shows.items():
                    try:
                        shows[show_id] = _entry(show_id, raw)
                    except ValueError as exc:
                        skipped[show_id] = raw
                        logger.error(
                            "Shows file %s: skipping show %r, which is not valid (%s)",
                            self.path,
                            show_id[:40],
                            str(exc).splitlines()[0],
                        )
        self._stamp, self._shows, self._skipped = stamp, shows, skipped
        return dict(shows)

    def _write_locked(self, shows: dict[str, Show]) -> None:
        entries: dict[str, Any] = {
            show_id: show.model_dump(mode="json") for show_id, show in shows.items()
        }
        for show_id, raw in self._skipped.items():
            entries.setdefault(show_id, raw)
        document = {"schema_version": SCHEMA_VERSION, "shows": entries}
        self.path.parent.mkdir(parents=True, exist_ok=True)
        atomic_write(self.path, json.dumps(document, indent=2, ensure_ascii=False) + "\n")
        try:
            stamp = self._stat()
        except OSError:
            stamp = None
        self._stamp, self._shows = stamp, dict(shows)

    def all(self) -> dict[str, Show]:
        """Every show; the shows last read when the file cannot be read just now."""
        with self._lock:
            try:
                return self._load_locked()
            except OSError as exc:
                logger.warning("Could not read the shows file %s: %s", self.path, exc)
                return dict(self._shows)

    def get(self, show_id: str) -> Show | None:
        """One show, or ``None``."""
        return self.all().get(show_id)

    def problem(self) -> str | None:
        """The shows the file skips, in words, or ``None``."""
        with self._lock:
            skipped = sorted(self._skipped)
        if not skipped:
            return None
        count = len(skipped)
        names = ", ".join(show_id[:40] for show_id in skipped[:5])
        more = f" and {count - 5} more" if count > 5 else ""
        return (
            f"{count} show{'' if count == 1 else 's'} in {self.path.name} "
            f"{'is' if count == 1 else 'are'} not valid and skipped until the file is "
            f"corrected: {names}{more}. AutoDJ keeps {'it' if count == 1 else 'them'} in the "
            "file as written."
        )

    def _check_name(self, shows: Mapping[str, Show], show_id: str | None, name: str) -> None:
        folded = name.casefold()
        for other_id, other in shows.items():
            if other_id != show_id and other.name.casefold() == folded:
                raise ShowError("name", f"A show named {other.name} already exists")

    def add(self, spec: ShowSpec) -> tuple[str, Show]:
        """Save a new show with an empty list.

        Raises:
            ShowError: The name is taken or the station has :data:`MAX_SHOWS`.
            OSError: The file could not be read or written; nothing is saved.
        """
        with self._lock:
            shows = self._load_locked()
            if len(shows) + len(self._skipped) >= MAX_SHOWS:
                raise ShowError("", f"A station keeps at most {MAX_SHOWS} shows")
            self._check_name(shows, None, spec.name)
            show_id = uuid.uuid4().hex
            show = Show(**spec.model_dump())
            self._write_locked({**shows, show_id: show})
            return show_id, show

    def update(self, show_id: str, change: Callable[[Show], Show]) -> Show:
        """Replace a show with ``change(show)``.

        Raises:
            KeyError: There is no such show.
            ShowError: The new name is taken.
            OSError: The file could not be read or written; nothing is saved.
        """
        with self._lock:
            shows = self._load_locked()
            show = change(shows[show_id])
            self._check_name(shows, show_id, show.name)
            self._write_locked({**shows, show_id: show})
            return show

    def delete(self, show_id: str) -> Show:
        """Remove a show.

        Raises:
            KeyError: There is no such show.
            OSError: The file could not be read or written; nothing is removed.
        """
        with self._lock:
            shows = self._load_locked()
            show = shows.pop(show_id)
            self._write_locked(shows)
            return show


def with_spec(show: Show, spec: ShowSpec) -> Show:
    """*show* with *spec*'s name, source and target; its list stays."""
    return show.model_copy(update=spec.model_dump())


def with_songs(show: Show, paths: Sequence[str], **fields: Any) -> Show:
    """*show* with the list *paths* (and *fields*, such as the generation note).

    Raises:
        ShowError: The list is too long or holds a path that is not text.
    """
    try:
        return Show.model_validate({**show.model_dump(), **fields, "songs": list(paths)})
    except ValidationError as exc:
        raise field_error(exc) from None


