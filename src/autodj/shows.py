@dataclass(frozen=True)
class Generated:
    """A generated list: its songs (paths), their total length and a note in words."""

    songs: list[str]
    seconds: float
    note: str


def _category_clock(show_id: str, category: str) -> tuple[dict[str, Any], list[Any]]:
    """A clockwheel of one step, the show's category at random, that is never saved."""
    from autodj.clockwheel import ClockSlot, validate_clock

    clock = {
        "version": 1,
        "name": f"show-{show_id}",
        "resync_minutes": [],
        "steps": [
            {"type": "category", "category": category, "selection": "random", "enforce_rules": True}
        ],
    }
    slots = validate_clock(
        [ClockSlot(kind="category", category=category, selection="random", enforce_rules=True)]
    )
    return clock, slots


def generate(
    source: Any,
    show_id: str,
    show: ShowSpec,
    *,
    start: float | None = None,
    seed: int | None = None,
    budget: float = GENERATE_SECONDS,
    cancelled: Callable[[], bool] | None = None,
) -> Generated:
    """Generate *show*'s list with a dry run of *source*'s picker (a SimulationSource).

    The dry run plays the show's category (as a one-step clockwheel that
    picks at random) or its clockwheel from *start* (now by default) until
    the songs reach the target length, under the station's repeat rules and
    DMCA limits; liners are left out, and for a category, so is any song
    outside it.  Nothing on the air changes.  Blocking: run it off the event
    loop.

    Raises:
        ShowError: The source is gone or holds no song, or nothing was picked.
    """
    from autodj.rotation_sim import (
        MAX_HOURS,
        SimulationError,
        SimulationRequest,
        simulate,
        snapshot_player,
    )

    library = source.library
    snapshot = source.snapshot or snapshot_player(source.player)
    members: frozenset[str] | None = None
    if show.source == "category":
        index = (
            library.categories_for(snapshot.station_paths)
            if hasattr(library, "categories_for")
            else getattr(library, "categories", None)
        )
        found = index.members() if index is not None else {}
        if show.category not in found:
            raise ShowError("category", "That category no longer exists; choose another")
        name, members = found[show.category]
        if not members:
            raise ShowError("category", f"Category {name} has no songs in the library")
        clock_name = f"show-{show_id}"
        override: tuple[dict[str, Any], list[Any]] | None = _category_clock(show_id, show.category)
    else:
        from autodj.clockwheel_store import ClockwheelStore
        from autodj.stations import StationPaths

        paths = snapshot.station_paths or StationPaths.default(snapshot.cfg)
        try:
            ClockwheelStore(paths.clockwheels).load(show.clockwheel)
        except (ValueError, OSError) as exc:
            raise ShowError("clockwheel", str(exc)) from None
        clock_name = show.clockwheel
        override = None
    cfg = copy.deepcopy(snapshot.cfg)
    cfg.playback.pick_mode = "clock"
    settings = {**snapshot.settings, "_pure_shuffle": False}
    run = replace(
        source,
        events=(),
        clockwheel=override,
        snapshot=replace(
            snapshot,
            cfg=cfg,
            settings=settings,
            discovery_enabled=False,
            clock={"name": clock_name, "cursor": 0},
            clock_status=None,
        ),
    )
    liners = {entry.path for entry in library.entries_snapshot("liner")}
    target = show.target_minutes * 60.0
    picked: list[str] = []
    seen: set[str] = set()
    total = 0.0
    outside = 0

    def on_pick(_at: float, entry: Any) -> None:
        nonlocal total, outside
        if entry.path in liners:
            return
        if (members is not None and entry.path not in members) or entry.path in seen:
            outside += 1
            return
        if total >= target or len(picked) >= MAX_SONGS:
            return
        picked.append(entry.path)
        seen.add(entry.path)
        total += max(0.0, float(entry.length or 0.0))

    def done() -> bool:
        return total >= target or len(picked) >= MAX_SONGS or bool(cancelled and cancelled())

    # Room for songs the category filter drops; the target ends the run first.
    hours = min(float(MAX_HOURS), max(1.0, target / 3600.0 * 4))
    try:
        report = simulate(
            run,
            SimulationRequest(hours=hours, start=start, seed=seed),
            cancelled=done,
            budget=budget,
            on_pick=on_pick,
        )
    except SimulationError as exc:
        raise ShowError("", str(exc)) from None
    if not picked:
        what = "category" if show.source == "category" else "clockwheel"
        raise ShowError(
            show.source, f"No song could be picked from the {what}; the list was not changed"
        )
    note = ""
    if total < target:
        stopped = report.get("stopped_reason")
        why = (
            "the time limit was reached"
            if stopped == "time limit"
            else "the songs the repeat rules and the DMCA limits allow ran out"
        )
        note = (
            f"The list is {length_text(total)}, shorter than the target of "
            f"{length_text(target)}: {why}."
        )
    return Generated(picked, total, note)


class ShowGenerations:
    """One generation at a time for the whole server, each on its own thread.

    A generation is short (:data:`GENERATE_SECONDS` at most) and runs below
    normal priority, so the audio and the web server keep their place.
    """

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._busy: tuple[threading.Thread, threading.Event] | None = None
        self._closing = False
        # The shows whose list is being generated and saved, by station and ID.
        self._shows: set[tuple[str, str]] = set()

    @contextlib.contextmanager
    def reserved(self, station: str, show_id: str, busy: str = "") -> Iterator[None]:
        """Hold one show's list while it is generated and saved, or changed, until the block ends.

        Raises:
            ShowBusy: That show's list is held already; *busy* says so, in words.
        """
        key = (station, show_id)
        with self._lock:
            if key in self._shows:
                raise ShowBusy(
                    "", busy or "This show's list is being generated or changed; try again shortly"
                )
            self._shows.add(key)
        try:
            yield
        finally:
            with self._lock:
                self._shows.discard(key)

    async def run(self, work: Callable[[Callable[[], bool]], Generated]) -> Generated:
        """Run ``work(cancelled)`` on a thread of its own and wait for it.

        Raises:
            ShowBusy: Another generation is running, or the server is shutting down.
        """
        loop = asyncio.get_running_loop()
        future: asyncio.Future[Generated] = loop.create_future()
        cancel = threading.Event()

        def deliver(result: Any, error: BaseException | None) -> None:
            if future.done():
                return
            if error is not None:
                future.set_exception(error)
            else:
                future.set_result(result)

        def body() -> None:
            from autodj.rotation_sim import lower_thread_priority

            lower_thread_priority()
            result: Any = None
            error: BaseException | None = None
            try:
                result = work(cancel.is_set)
            except BaseException as exc:  # handed to the waiting route
                error = exc
            finally:
                with self._lock:
                    self._busy = None
            with contextlib.suppress(RuntimeError):  # the loop closed at shutdown
                loop.call_soon_threadsafe(deliver, result, error)

        thread = threading.Thread(target=body, name="autodj-show-generate", daemon=True)
        with self._lock:
            if self._closing:
                raise ShowBusy("", "The server is shutting down")
            if self._busy is not None:
                raise ShowBusy("", "Another show's list is being generated; try again shortly")
            self._busy = (thread, cancel)
        try:
            thread.start()
        except Exception:
            with self._lock:
                self._busy = None
            raise
        try:
            return await asyncio.shield(future)
        except asyncio.CancelledError:
            cancel.set()
            raise

    def shutdown(self, timeout: float) -> bool:
        """Cancel the running generation and wait up to *timeout* seconds; whether it ended."""
        with self._lock:
            self._closing = True
            busy = self._busy
        if busy is None:
            return True
        thread, cancel = busy
        cancel.set()
        thread.join(timeout)
        return not thread.is_alive()


