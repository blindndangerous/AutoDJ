"""Shows (#106): a named list of songs, prepared ahead, that airs at a scheduled time.

A show such as "Remembering the 2000s" is planned in three steps:

1. Its source: a rotation category (genre, year, any beets field or a
   playlist, see :mod:`autodj.categories`) or a clockwheel, whose steps may
   use conditions and categories, and a target length.
2. Its list, generated by a dry run of the station's own picker (the
   rotation tester's, :mod:`autodj.rotation_sim`), so the repeat rules and
   the DMCA limits shape it as they shape live picks; nothing on the air
   changes.  The list is then the operator's: reorder it, remove songs, add
   songs from the library, or generate it again.
3. A schedule event, "Play a show", at a date and time.

On the air (:class:`ShowRunner`) the list feeds the user queue a couple of
songs ahead, so liners, time checks and breaks behave as they do with any
queued song, and the station's own picking resumes when the list ends.
Show songs are pre-approved: the repeat rules do not hold them back.  The
DMCA limits are checked again just before each song is queued and at every
song change while it waits: a song that would break one is skipped, and
the skip is logged and shown.

Each station keeps its shows in ``shows.json`` in its state folder.  One
show in the file that is not valid is skipped, logged and said on the page,
and written back as it was with every save; a file that is not a file of
shows at all is set aside as ``shows.json.bad-<id>``; one that cannot be read
just now is left alone, the shows last read are used and saves are refused.
"""

