MAX_SKIPPED = 50
_ID = re.compile(r"[0-9a-f]{32}")

Source = Literal["category", "clockwheel"]


class ShowError(ValueError):
    """A show that cannot be saved, generated or started, naming the field at fault."""

    def __init__(self, field_name: str, message: str) -> None:
        super().__init__(message)
        self.field = field_name
        self.message = message


class ShowBusy(ShowError):
    """Another generation is running, or the server is shutting down."""


Name = Annotated[
    StrictStr, StringConstraints(strip_whitespace=True, min_length=1, max_length=NAME_MAX)
]
SongPath = Annotated[StrictStr, StringConstraints(min_length=1, max_length=4096)]

FIELD_LABELS = {
    "name": "Name",
    "source": "Songs come from",
    "category": "Category",
    "clockwheel": "Clockwheel",
    "target_minutes": "Target length (minutes)",
    "songs": "Songs",
}


class ShowSpec(BaseModel):
    """What the operator chooses: the name, where the songs come from and how long."""

    model_config = ConfigDict(extra="forbid")

    name: Name
    source: Source
    category: Annotated[StrictStr, StringConstraints(max_length=64)] = ""
    clockwheel: Annotated[StrictStr, StringConstraints(max_length=64)] = ""
    target_minutes: StrictInt = Field(
        default=DEFAULT_TARGET_MINUTES, ge=MIN_TARGET_MINUTES, le=MAX_TARGET_MINUTES
    )

    @model_validator(mode="after")
    def _one_source(self) -> Self:
        """Require the field the source uses and clear the other."""
        if self.source == "category":
            if not re.fullmatch(r"[A-Za-z0-9_-]{1,64}", self.category):
                raise ShowError("category", "Choose a category")
            self.clockwheel = ""
        else:
            if not self.clockwheel.strip():
                raise ShowError("clockwheel", "Choose a clockwheel")
            self.category = ""
        return self


class Show(ShowSpec):
    """A saved show: the spec, its list of songs (file paths) and how it was made."""

    songs: list[SongPath] = Field(default_factory=list, max_length=MAX_SONGS)
    generated_at: float | None = None
    note: Annotated[StrictStr, StringConstraints(max_length=500)] = ""


def field_error(exc: ValidationError) -> ShowError:
    """The first error in *exc* as a :class:`ShowError` naming its field."""
    error = exc.errors()[0]
    original = (error.get("ctx") or {}).get("error")
    if isinstance(original, ShowError):
        return original
    location = [str(part) for part in error.get("loc", ())]
    name = location[0] if location else ""
    if error.get("type") == "extra_forbidden":
        return ShowError(name, f"Unknown field {name}")
    if name == "name":
        return ShowError("name", f"Enter a name of up to {NAME_MAX} characters")
    if name == "target_minutes":
        return ShowError(
            name,
            f"Target length must be a whole number of minutes from {MIN_TARGET_MINUTES} "
            f"to {MAX_TARGET_MINUTES}",
        )
    if name == "songs":
        return ShowError(name, f"A show holds at most {MAX_SONGS} songs")
    return ShowError(name, f"{FIELD_LABELS.get(name, name)}: {error['msg']}")


def parse_spec(body: Mapping[str, Any]) -> ShowSpec:
    """Check a show's spec from the page.

    Raises:
        ShowError: A value is not valid; names its field.
    """
    try:
        return ShowSpec.model_validate(dict(body))
    except ValidationError as exc:
        raise field_error(exc) from None


class _ShowsFile(BaseModel):
    """The file's frame; each show in it is checked on its own."""

    model_config = ConfigDict(extra="forbid")

    schema_version: Literal[1]
    shows: dict[str, Any] = Field(default_factory=dict)


def _entry(show_id: str, raw: Any) -> Show:
    if not _ID.fullmatch(show_id):
        raise ValueError("its ID is not 32 hexadecimal digits")
    return Show.model_validate(raw)


